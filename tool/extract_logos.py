RING_OUT = 12  # px beyond the approximate radius scanned per ray
RING_TRIM = 0.7  # keep the best 70 % of edge samples when refitting
FEATHER = 1.5  # px, circular alpha edge


def clamp(v, lo=0.0, hi=1.0):
    return lo if v < lo else hi if v > hi else v


# ---------------------------------------------------------------- keying ---
def key_alpha(img, key, classes, gain, cutoff, remap=None):
    """Return (alpha list 0..1, un-premultiplied RGB list) for img."""
    w, h = img.size
    px = img.load()
    dirs = []
    for c in classes:
        u = (c[0] - key[0], c[1] - key[1], c[2] - key[2])
        dirs.append((u, float(u[0] ** 2 + u[1] ** 2 + u[2] ** 2)))
    alpha = [0.0] * (w * h)
    rgb = [(0, 0, 0)] * (w * h)
    for y in range(h):
        for x in range(w):
            p = px[x, y]
            v = (p[0] - key[0], p[1] - key[1], p[2] - key[2])
            best_a, best_res = 0.0, None
            for u, uu in dirs:
                a = clamp((v[0] * u[0] + v[1] * u[1] + v[2] * u[2]) / uu)
                r = ((v[0] - a * u[0]) ** 2 + (v[1] - a * u[1]) ** 2 +
                     (v[2] - a * u[2]) ** 2)
                if best_res is None or r < best_res:
                    best_a, best_res = a, r
            a = clamp(best_a * gain)
            if remap is not None:
                a = clamp((a - remap[0]) / (remap[1] - remap[0]))
            if a < cutoff:
                a = 0.0
            i = y * w + x
            alpha[i] = a
            if a > 0:
                # px = key*(1-a) + fg*a  =>  fg = key + (px-key)/a
                rgb[i] = tuple(int(round(clamp(key[k] + v[k] / a, 0, 255)))
                               for k in range(3))
    return alpha, rgb


def components(mask, w, h):
    """8-connected components of a boolean list; yields lists of indices."""
    seen = bytearray(w * h)
    for start in range(w * h):
        if not mask[start] or seen[start]:
            continue
        comp = [start]
        seen[start] = 1
        q = deque([start])
        while q:
            i = q.popleft()
            x, y = i % w, i // w
            for dy in (-1, 0, 1):
                yy = y + dy
                if yy < 0 or yy >= h:
                    continue
                for dx in (-1, 0, 1):
                    xx = x + dx
                    if 0 <= xx < w:
                        j = yy * w + xx
                        if mask[j] and not seen[j]:
                            seen[j] = 1
                            comp.append(j)
                            q.append(j)
        yield comp


def remove_specks(alpha, w, h, min_px):
    for comp in components([a > 0 for a in alpha], w, h):
        if len(comp) < min_px or max(alpha[i] for i in comp) < 0.5:
            for i in comp:
                alpha[i] = 0.0


def fill_holes(alpha, rgb, img, w, h):
    """Make transparent regions not connected to the crop border opaque."""
    px = img.load()
    for comp in components([a < 0.5 for a in alpha], w, h):
        touches = any(i % w in (0, w - 1) or i // w in (0, h - 1)
                      for i in comp)
        if not touches:
            for i in comp:
                alpha[i] = 1.0
                rgb[i] = px[i % w, i // w]


def to_rgba(alpha, rgb, w, h):
    out = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    out.putdata([(c[0], c[1], c[2], int(round(a * 255))) if a > 0
                 else (0, 0, 0, 0) for a, c in zip(alpha, rgb)])
    return out


def tight_pad(im):
    bbox = im.getchannel('A').getbbox()
    im = im.crop(bbox)
    pad = int(math.ceil(PAD_FRACTION * max(im.size)))
    out = Image.new('RGBA', (im.width + 2 * pad, im.height + 2 * pad),
                    (0, 0, 0, 0))
    out.paste(im, (pad, pad))
    return out


def extract_keyed(cfg):
    src = Image.open(os.path.join(SRC, cfg['src'])).convert('RGB')
    img = src.crop(cfg['box'])
    w, h = img.size
    alpha, rgb = key_alpha(img, cfg['key'], cfg['classes'], cfg['gain'],
                           cfg['cutoff'])
    remove_specks(alpha, w, h, cfg['speck'])
    if cfg['fill_holes']:
        fill_holes(alpha, rgb, img, w, h)
    return tight_pad(to_rgba(alpha, rgb, w, h))


# ------------------------------------------------------------ medallions ---
def ring_test(kind):
    if kind == 'gold':
        return lambda p: p[0] > 120 and p[0] - p[2] > 45
    return lambda p: (abs(p[0] - 248) + abs(p[1] - 248) + abs(p[2] - 242)) > 45


def fit_circle(pts):
    """Algebraic (Kasa) least-squares circle fit -> (cx, cy, r)."""
    n = float(len(pts))
    mx = sum(p[0] for p in pts) / n
    my = sum(p[1] for p in pts) / n
    suu = suv = svv = suuu = svvv = suvv = svuu = 0.0
    for x, y in pts:
        u, v = x - mx, y - my
        suu += u * u
        suv += u * v
        svv += v * v
        suuu += u * u * u
        svvv += v * v * v
        suvv += u * v * v
        svuu += v * u * u
    b1 = 0.5 * (suuu + suvv)
    b2 = 0.5 * (svvv + svuu)
    det = suu * svv - suv * suv
    uc = (b1 * svv - b2 * suv) / det
    vc = (suu * b2 - suv * b1) / det
    r = math.sqrt(uc * uc + vc * vc + (suu + svv) / n)
    return mx + uc, my + vc, r


def detect_ring(img, c, r, kind, rays=360):
    """Return (cx, cy, outer_radius) of the ring's outer edge.

    Along each ray from the approximate centre, the outermost ring-coloured
    pixel within [r - RING_SEARCH_R, r + RING_OUT] is an outer-edge sample.  A circle is fitted to the samples, outliers (rays that ran into
    neighbouring ornaments) are trimmed, and the fit is repeated.
    """
    px = img.load()
    test = ring_test(kind)
    pts = []
    for k in range(rays):
        t = 2 * math.pi * k / rays
        ct, st = math.cos(t), math.sin(t)
        end = None
        for rr in range(r - RING_SEARCH_R, r + RING_OUT + 1):
            if test(px[int(round(c[0] + rr * ct)), int(round(c[1] + rr * st))]):
                end = rr
        if end is not None:
            pts.append((c[0] + (end + 0.5) * ct, c[1] + (end + 0.5) * st))
    cx, cy, rad = fit_circle(pts)
    for _ in range(3):
        res = sorted(abs(math.hypot(x - cx, y - cy) - rad) for x, y in pts)
        lim = max(1.5, res[int(len(res) * RING_TRIM)])
        pts = [p for p in pts if abs(math.hypot(p[0] - cx, p[1] - cy) - rad)
               <= lim]
        cx, cy, rad = fit_circle(pts)
    return int(round(cx)), int(round(cy)), int(math.floor(rad))


def extract_medallion(cfg):
    src = Image.open(os.path.join(SRC, cfg['src'])).convert('RGB')
    cx, cy, rad = detect_ring(src, cfg['c'], cfg['r'], cfg['ring'])
    R = rad + 1.0
    pad = int(math.ceil(PAD_FRACTION * 2 * R))
    half = int(math.ceil(R)) + pad
    box = (cx - half, cy - half, cx + half + 1, cy + half + 1)
    img = src.crop(box).convert('RGBA')
    w, h = img.size
    mask = Image.new('L', (w, h), 0)
    ox, oy = cx - box[0], cy - box[1]
    data = []
    for y in range(h):
        for x in range(w):
            d = math.hypot(x - ox, y - oy)
            data.append(int(round(255 * clamp((R - d) / FEATHER + 0.5))))
    mask.putdata(data)
    img.putalpha(mask)
    return img, (cx, cy, rad)


def extract_navy_title(med_info):
    cfg = NAVY_TITLE
    cx, cy, rad = med_info
    inner = rad - cfg['inset']
    src = Image.open(os.path.join(SRC, cfg['src'])).convert('RGB')
    box = (cx - inner, cy - inner, cx + inner, cy + inner)
    img = src.crop(box)
    w, h = img.size
    alpha, rgb = key_alpha(img, cfg['key'], cfg['classes'], cfg['gain'],
                           cfg['cutoff'], remap=(cfg['remap_lo'],
                                                 cfg['remap_hi']))
    for y in range(h):
        for x in range(w):
            if math.hypot(x - inner, y - inner) > inner - 1:
                alpha[y * w + x] = 0.0
    remove_specks(alpha, w, h, cfg['speck'])
    return tight_pad(to_rgba(alpha, rgb, w, h))


# ----------------------------------------------------------- QA sheet ------
def checker(size, cell=12):
    im = Image.new('RGB', size, (255, 255, 255))
    px = im.load()
    for y in range(size[1]):
        for x in range(size[0]):
            if (x // cell + y // cell) % 2:
                px[x, y] = (200, 200, 200)
    return im


def contact_sheet(assets, path):
    bgs = {
        'title_white': [(11, 31, 56), (8, 50, 38)],
        'finial_gold': [(11, 31, 56), (8, 50, 38)],
        'title_gold': [(14, 32, 55), (8, 50, 38)],
        'dome_green': [(12, 31, 52), (245, 238, 220)],
        'medallion_emerald': [(8, 50, 38), (11, 31, 56)],
        'medallion_emerald_b': [(8, 50, 38), (11, 31, 56)],
        'medallion_ivory': [(248, 248, 242), (11, 31, 56)],
        'title_navy': [(248, 248, 242), (240, 228, 200)],
    }
    cell_w = 620
    rows = []
    for name, im in assets.items():
        s = min(1.0, cell_w / im.width)
        sm = im.resize((max(1, int(im.width * s)), max(1, int(im.height * s))),
                       Image.LANCZOS)
        tiles = []
        for bg in bgs[name]:
            t = Image.new('RGB', sm.size, bg)
            t.paste(sm, (0, 0), sm)
            tiles.append(t)
        ch = checker(sm.size)
        ch.paste(sm, (0, 0), sm)
        tiles.append(ch)
        rows.append(tiles)
    W = 3 * (cell_w + 10) + 10
    H = sum(r[0].height + 10 for r in rows) + 10
    sheet = Image.new('RGB', (W, H), (128, 128, 128))
    y = 10
    for tiles in rows:
        x = 10
        for t in tiles:
            sheet.paste(t, (x, y))
            x += cell_w + 10
        y += tiles[0].height + 10
    sheet.save(path)


def main(argv):
    os.makedirs(OUT, exist_ok=True)
    assets = {}
    for name, cfg in KEYED.items():
        assets[name] = extract_keyed(cfg)
    rings = {}
    for name, cfg in MEDALLIONS.items():
        assets[name], rings[name] = extract_medallion(cfg)
        print('%s ring centre=(%d, %d) outer radius=%d' % ((name,) +
                                                            rings[name]))
    assets['title_navy'] = extract_navy_title(rings['medallion_ivory'])
    for name, im in assets.items():
        im.save(os.path.join(OUT, name + '.png'), optimize=True)
        print('%-20s %dx%d' % (name + '.png', im.width, im.height))
    if '--sheet' in argv:
        contact_sheet(assets, argv[argv.index('--sheet') + 1])


if __name__ == '__main__':
    main(sys.argv[1:])
