#!/usr/bin/env python3
"""Extract reusable transparent-PNG logo assets from the AI mock-ups.

Run from the repo root (pure Pillow, no numpy required):

    python3 -I tool/extract_logos.py                 # writes assets/logos/*.png
    python3 -I tool/extract_logos.py --sheet out.png # also writes a QA contact sheet

Every crop box, key colour and threshold is recorded below as a constant so the
assets can be regenerated byte-for-byte from the files in templates/.

Technique
---------
* Keyed assets (titles, finial, dome): the background is a near-uniform key
  colour.  Each pixel is modelled as ``key + a * (fg - key)`` for a small set of
  reference foreground colours ("classes"); the class with the smallest residual
  wins and gives the alpha ``a`` (scaled by GAIN so stroke interiors become fully
  opaque, then a low CUTOFF removes JPEG noise).  Colour is then
  un-premultiplied against the key, ``fg = key + (px - key) / a``, so the soft
  edges carry the stroke colour and do not leave a navy/ivory halo.
* Small connected components (JPEG specks, bits of neighbouring ornaments) are
  dropped; for the dome, enclosed transparent holes (dark windows) are refilled.
* Medallions: the outer edge of the gold ring is found by scanning circles
  around an approximate centre; the asset is that disc, opaque inside, with a
  ~1.5 px feathered circular alpha edge.
"""

